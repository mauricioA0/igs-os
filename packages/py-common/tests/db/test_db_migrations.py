import asyncio

import asyncpg
import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected


async def _counts(url: str) -> tuple[int, int, int]:
    conn = await asyncpg.connect(url)
    try:
        tables = await conn.fetchval(
            "SELECT count(*) FROM pg_tables WHERE schemaname = 'public' "
            "AND tablename <> 'alembic_version'"
        )
        enums = await conn.fetchval("SELECT count(*) FROM pg_type WHERE typtype = 'e'")
        policies = await conn.fetchval("SELECT count(*) FROM pg_policies")
        return tables, enums, policies
    finally:
        await conn.close()


def test_upgrade_downgrade_roundtrip(db_url: str, alembic_cfg: Config) -> None:
    cfg = alembic_cfg

    command.upgrade(cfg, "head")
    tables, enums, policies = asyncio.run(_counts(db_url))
    assert tables == 36
    assert enums > 0
    assert policies == 34  # every table except `tenants` and `llm_spend_daily`

    # Models and migrations agree (no autogenerate drift).
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"models drifted from migrations: {exc}")

    command.downgrade(cfg, "base")
    assert asyncio.run(_counts(db_url)) == (0, 0, 0)

    # And back up, so the downgrade left nothing behind that blocks a re-run.
    command.upgrade(cfg, "head")
    assert asyncio.run(_counts(db_url))[0] == 36
